// アプリ全体で使うフォント(書体)を1箇所にまとめた定数。
// 「文字が統一されていない(ページによって書体がちぐはぐに見える)」という
// ご指摘への対応。
//
// 【原因】index.html/CSSにアプリ全体のフォントを指定する記述が無く、各ページの
// 一番外側の要素だけが個別に fontFamily:'sans-serif' を指定していたため、
// これを指定していない部分(ヘッダー・ハンバーガーメニュー・見守り
// ダッシュボードの外枠など)はブラウザの既定フォント(多くの環境で
// "Times New Roman"のような明朝体/セリフ体)がそのまま表示されてしまい、
// ページ本文(ゴシック体/サンセリフ体)と見た目がちぐはぐになっていた。
// また、input・buttonなどのフォーム部品はブラウザの既定で親要素のフォント
// を引き継がない仕様のため、同じページ内でもラベル文字と入力欄の文字が
// 違う書体で表示されてしまっていた(themeContext.jsx側でこちらも合わせて
// 修正している)。
//
// 【対応方針】「グーグルが使用している一般的な文字に統一してほしい」という
// ご要望を踏まえ、Googleの標準書体であるRobotoを先頭に、OSごとの標準的な
// ゴシック体(日本語表示用のフォントも含む)へ順にフォールバックする構成に
// している。外部フォントファイルの読み込みは行わない(通信環境に依存せず、
// 端末に既に入っている書体だけで完結させるため)。
// ===================================================================
export const FONT_FAMILY =
  'Roboto, "Segoe UI", "Hiragino Kaku Gothic ProN", "Yu Gothic", Meiryo, "Noto Sans JP", Arial, sans-serif';
